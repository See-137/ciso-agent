"""Write `config/governance-ruleset.provisional.json` from the packaged default ruleset.

The governance loader never merges ruleset files: a deployment ruleset REPLACES the
default. So the deployment file is derived, never edited by hand: it is the packaged
`src/ciso/governance/rulesets/default.json` plus `DEPLOYMENT_ADDITIONS` (the assistant's
own configuration files, which the vendor-neutral default may not name), with its own
version and description. `tests/governance/test_deployment_ruleset.py` fails when the
committed file differs from what this script produces.

Run from the repository root after changing the default or the additions:

    uv run python config/derive_governance_ruleset.py           # rewrite the file
    uv run python config/derive_governance_ruleset.py --check   # exit 1 if stale
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any, Final

ROOT: Final = Path(__file__).resolve().parent.parent
DEFAULT_PATH: Final = ROOT / "src" / "ciso" / "governance" / "rulesets" / "default.json"
OUTPUT_PATH: Final = ROOT / "config" / "governance-ruleset.provisional.json"

#: Patterns ADDED to the default's lists in the deployment file.
DEPLOYMENT_ADDITIONS: Final[dict[str, tuple[str, ...]]] = {
    "agent_config_paths": ("**/CLAUDE.md", "**/.claude/**", "**/.mcp.json", "**/.claude.json"),
}
VERSION_PREFIX: Final = "deployment."


def derive(default: dict[str, Any]) -> dict[str, Any]:
    """The deployment ruleset for `default` (a parsed default ruleset). Pure."""
    out = dict(default)
    for key, extra in DEPLOYMENT_ADDITIONS.items():
        current = list(default.get(key, []))
        out[key] = current + [p for p in extra if p not in current]
    base = default["version"]
    out["version"] = VERSION_PREFIX + base
    out["description"] = (
        "PROVISIONAL deployment ruleset for the local build. GENERATED by "
        "config/derive_governance_ruleset.py; do not edit by hand. The governance loader "
        "never merges ruleset files, so this file REPLACES the packaged default: it is "
        f"src/ciso/governance/rulesets/default.json ({base}) unchanged, plus the "
        "assistant's own instruction and settings files added to agent_config_paths "
        "(the vendor-neutral default leaves them out). "
        "tests/governance/test_deployment_ruleset.py fails when this file differs from "
        "what the script produces. Not an approved company policy."
    )
    return out


def render(default_path: Path = DEFAULT_PATH) -> str:
    default = json.loads(default_path.read_text(encoding="utf-8"))
    return json.dumps(derive(default), indent=2, ensure_ascii=False) + "\n"


def main(argv: list[str]) -> int:
    text = render()
    if argv[1:] == ["--check"]:
        current = OUTPUT_PATH.read_text(encoding="utf-8") if OUTPUT_PATH.exists() else ""
        return 0 if current == text else 1
    if argv[1:]:
        sys.stderr.write("usage: derive_governance_ruleset.py [--check]\n")
        return 2
    OUTPUT_PATH.write_text(text, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
